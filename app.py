
import os
import joblib
import streamlit as st
import pandas as pd
import plotly.express as px

# Use the folder from which Streamlit is launched
BASE_DIR = os.getcwd()

print("Current working directory:", BASE_DIR)
print("Files available:", os.listdir(BASE_DIR))

# --------------------------------------------------
# PAGE CONFIGURATION
# --------------------------------------------------
st.set_page_config(
    page_title="Mobile Intelligence Hub",
    page_icon="📱",
    layout="wide"
)

# --------------------------------------------------
# LOAD PROJECT DATA
# --------------------------------------------------

@st.cache_data
def load_data():
    products_path = os.path.join(
        BASE_DIR, "product_data.pkl"
    )

    reviews_path = os.path.join(
        BASE_DIR, "cleaned_reviews.pkl"
    )

    similarity_path = os.path.join(
        BASE_DIR, "similarity_matrix.pkl"
    )

    products = joblib.load(products_path)
    reviews = joblib.load(reviews_path)
    similarity = joblib.load(similarity_path)

    return products, reviews, similarity


product_df, df_clean, similarity_df = load_data()

# --------------------------------------------------
# SIDEBAR
# --------------------------------------------------
st.sidebar.title("📱 Mobile Intelligence Hub")

page = st.sidebar.radio(
    "Navigate",
    [
        "Dashboard",
        "Product Segmentation",
        "Recommendations"
    ]
)

# --------------------------------------------------
# DASHBOARD
# --------------------------------------------------
if page == "Dashboard":

    st.title("📱 Mobile Product Intelligence Dashboard")

    st.write(
        "Explore mobile reviews, pricing, product segments, "
        "and similar mobile phones."
    )

    col1, col2, col3, col4 = st.columns(4)

    col1.metric(
        "Total Reviews",
        f"{len(df_clean):,}"
    )

    col2.metric(
        "Mobile Models",
        product_df["model"].nunique()
    )

    col3.metric(
        "Brands",
        product_df["brand"].nunique()
    )

    col4.metric(
        "Average Rating",
        f"{df_clean['rating'].mean():.2f}/5"
    )

    st.subheader("Reviews by Brand")

    brand_counts = (
        df_clean.groupby("brand")
        .size()
        .reset_index(name="Review Count")
        .sort_values("Review Count", ascending=False)
    )

    fig = px.bar(
        brand_counts,
        x="brand",
        y="Review Count",
        color="brand",
        title="Number of Reviews by Brand"
    )

    st.plotly_chart(fig, use_container_width=True)

    st.subheader("Price vs Average Rating")

    fig = px.scatter(
        product_df,
        x="median_price_usd",
        y="average_rating",
        color="brand",
        size="review_count",
        hover_name="model",
        title="Mobile Price vs Average Rating"
    )

    st.plotly_chart(fig, use_container_width=True)

# --------------------------------------------------
# PRODUCT SEGMENTATION
# --------------------------------------------------
elif page == "Product Segmentation":

    st.title("Product Segmentation")

    st.write(
        "Explore the groups generated by the K-Means model."
    )

    selected_cluster = st.selectbox(
        "Select a cluster",
        sorted(product_df["cluster"].unique())
    )

    filtered_products = product_df[
        product_df["cluster"] == selected_cluster
    ]

    st.subheader(
        f"Products in Cluster {selected_cluster}"
    )

    st.dataframe(
        filtered_products,
        use_container_width=True
    )

    fig = px.scatter(
        product_df,
        x="median_price_usd",
        y="average_rating",
        color=product_df["cluster"].astype(str),
        hover_name="model",
        title="K-Means Product Segments",
        labels={"color": "Cluster"}
    )

    st.plotly_chart(fig, use_container_width=True)

# --------------------------------------------------
# RECOMMENDATIONS
# --------------------------------------------------
elif page == "Recommendations":

    st.title("Similar Mobile Recommendations")

    selected_model = st.selectbox(
        "Choose a mobile phone",
        product_df["model"].tolist()
    )

    top_n = st.slider(
        "Number of recommendations",
        min_value=1,
        max_value=10,
        value=5
    )

    if st.button("Find Similar Phones"):

        product_index = product_df.index[
            product_df["model"] == selected_model
        ][0]

        scores = similarity_df.loc[product_index]

        ranked_indices = scores.sort_values(
            ascending=False
        ).index

        ranked_indices = [
            idx for idx in ranked_indices
            if idx != product_index
        ]

        recommendations = product_df.loc[
            ranked_indices[:top_n],
            [
                "brand",
                "model",
                "median_price_usd",
                "average_rating",
                "cluster"
            ]
        ].copy()

        recommendations["similarity_score"] = [
            scores.loc[idx]
            for idx in recommendations.index
        ]

        st.subheader(
            f"Recommendations for {selected_model}"
        )

        st.dataframe(
            recommendations.reset_index(drop=True),
            use_container_width=True
        )

st.sidebar.divider()
st.sidebar.caption("Built with Python, Scikit-learn and Streamlit")
